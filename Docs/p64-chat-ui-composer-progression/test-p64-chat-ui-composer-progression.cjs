const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const panel = read('src/client/GroupChatPanel.tsx')
const dock = read('src/client/GroupChatSideDock.tsx')
const composer = read('src/client/GroupChatComposer.tsx')

assert.match(panel, /role="log"/, 'middle message stream exposes a log region')
assert.match(panel, /aria-live="polite"/, 'new messages are announced as additions')
assert.match(panel, /setMessages\(prev=>prev\.some\(m=>m\.messageId===data\.message\.messageId\)\?prev:\[\.\.\.prev,data\.message\]\)/, 'sent user message is appended immediately after API success')
assert.match(panel, /setDraft\(''\)/, 'composer is cleared after successful send')
assert.match(panel, /useLayoutEffect/, 'message progression uses layout-timed bottom sync')
assert.match(panel, /requestAnimationFrame\(\(\)=>\{sync\(\);requestAnimationFrame\(sync\)\}\)/, 'bottom sync is retried after render/layout')
assert.match(composer, /disabled=\{sending \|\| !value\.trim\(\)\}/, 'send button is disabled for empty drafts')
assert.match(composer, /onKeyDown=\{e => \{[\s\S]*Enter[\s\S]*!e\.shiftKey[\s\S]*onSend\(\)/, 'Enter sends and Shift+Enter keeps multiline input')
assert.match(panel, /padding-right:min\(var\(--dsh-group-chat-hud-overlay-width,360px\),max\(0px,calc\(100% - 320px\)\)\)/, 'HUD avoidance is capped by middle tab width, not 100vw')
assert.match(panel, /@media\(max-width:760px\)[\s\S]*\.gc-conversation\{padding-right:44px;\}/, 'narrow viewport keeps a readable center surface')
assert.match(dock, /@media\(max-width:760px\)[\s\S]*translateX\(calc\(100% - 44px\)\)/, 'narrow docked HUD becomes a slim reveal strip instead of covering the chat')
assert.doesNotMatch(dock, /GroupChatPanel/, 'HUD does not duplicate the central chat input panel')

