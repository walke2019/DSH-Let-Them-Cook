const fs = require('node:fs')
const path = require('node:path')
const root = process.cwd()
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const assert = (ok, msg) => { if (!ok) throw new Error(msg) }

const client = read('src/client/index.ts')
const hero = read('src/client/GroupChatHeroEntry.tsx')
const layout = read('src/client/layout-push.ts')
const sideDock = read('src/client/GroupChatSideDock.tsx')
const panel = read('src/client/GroupChatPanel.tsx')
const composer = read('src/client/GroupChatComposer.tsx')

assert(!client.includes('conversation.hero.agentPreset'), 'new-session entry must not collide with the single official agent preset hero slot')
assert(sideDock.includes('GroupChatHeroEntry'), 'side dock must expose the global launcher while Agent tab is inactive')
assert(sideDock.includes('const hudSurfaceActive = extensionTabActive || heroMainActive'), 'HUD must be available while the temporary group-chat surface is open')
assert(sideDock.includes('{!extensionTabActive && <GroupChatHeroEntry />}'), 'launcher must stay mounted while the temporary group-chat surface is open')
assert(sideDock.includes('if (heroMainActive) setIsOpen(true)'), 'temporary group-chat surface should auto-open the original HUD/sidebar')
assert(client.includes('conversation.input.left') && client.includes('GroupChatInputEntry'), 'official composer must expose a small Agent group chat shortcut')
assert(hero.includes('data-dsh-group-chat-hero-entry'), 'hero entry DOM marker missing')
assert(hero.includes('进入 Agent 群聊') && hero.includes('Open Agent group chat'), 'hero entry must be bilingual')
assert(hero.includes('clickVisibleGroupChatTab'), 'entry must switch to the real middle Agent tab when available')
assert(hero.includes('dsh-group-chat:open-hero-main'), 'official composer shortcut must be able to open the fallback main surface')
assert(hero.includes('id="dsh-group-chat-hero-main"'), 'new-session fallback must show a main surface, not only a hint')
assert(hero.includes('gc-hero-main-body'), 'fallback main surface body missing')
assert(hero.includes('<GroupChatPanel mode="dock" />'), 'new-session fallback must show the group-chat composer and message view')
assert(hero.includes('回到源对话') && hero.includes('Back to source chat'), 'fallback surface needs a clear way back to official chat')
assert(!hero.includes("data-dsh-group-chat-tab-active', 'true'"), 'launcher must not masquerade as the real Agent tab or it unmounts itself before opening')
assert(!hero.includes('role="dialog"'), 'fallback should be a center work surface, not a modal dialog window')
assert(hero.includes('position:fixed;right:0;top:118px'), 'launcher must be visible on fresh official chats')
assert(!client.includes('conversation.body'), 'plugin must not take over conversation.body')
assert(!layout.includes('body[data-dsh-group-chat-hero-open="true"] [data-composer-seat]'), 'hero entry must not globally hide official composer via layout CSS')
assert(panel.includes('.gc-chat-bottom{position:relative;flex:0 0 auto;'), 'group-chat composer must stay as a non-scrolling bottom flex child')
assert(panel.includes('body[data-dsh-group-chat-hero-open="true"][data-dsh-group-chat-hud-docked-open="true"] .gc-conversation'), 'temporary surface must avoid the HUD just like the real Agent tab')
assert(composer.includes('grid-template-areas:"mention tier help send" "hint hint hint send"'), 'send button must stay in the bottom-right grid area')
assert(composer.includes('.gc-send { grid-area:send; align-self:end; justify-self:end;'), 'send button position guard missing')

